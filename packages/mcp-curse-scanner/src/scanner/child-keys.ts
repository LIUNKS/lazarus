// ES5 node types and the order of their child properties (source order).
export const CHILD_KEYS: Readonly<Record<string, readonly string[]>> = {
  Program: ['body'],
  BlockStatement: ['body'],
  ExpressionStatement: ['expression'],
  IfStatement: ['test', 'consequent', 'alternate'],
  ConditionalExpression: ['test', 'consequent', 'alternate'],
  ForStatement: ['init', 'test', 'update', 'body'],
  ForInStatement: ['left', 'right', 'body'],
  WhileStatement: ['test', 'body'],
  DoWhileStatement: ['body', 'test'],
  SwitchStatement: ['discriminant', 'cases'],
  SwitchCase: ['test', 'consequent'],
  TryStatement: ['block', 'handler', 'finalizer'],
  CatchClause: ['param', 'body'],
  FunctionDeclaration: ['id', 'params', 'body'],
  FunctionExpression: ['id', 'params', 'body'],
  VariableDeclaration: ['declarations'],
  VariableDeclarator: ['id', 'init'],
  AssignmentExpression: ['left', 'right'],
  BinaryExpression: ['left', 'right'],
  LogicalExpression: ['left', 'right'],
  UnaryExpression: ['argument'],
  UpdateExpression: ['argument'],
  ReturnStatement: ['argument'],
  ThrowStatement: ['argument'],
  CallExpression: ['callee', 'arguments'],
  NewExpression: ['callee', 'arguments'],
  MemberExpression: ['object', 'property'],
  ArrayExpression: ['elements'],
  ObjectExpression: ['properties'],
  Property: ['key', 'value'],
  SequenceExpression: ['expressions'],
  LabeledStatement: ['label', 'body'],
  BreakStatement: ['label'],
  ContinueStatement: ['label'],
  WithStatement: ['object', 'body'],
  Identifier: [],
  Literal: [],
  ThisExpression: [],
  EmptyStatement: [],
  DebuggerStatement: [],
};

export function childKeysOf(type: string): readonly string[] | undefined {
  return Object.hasOwn(CHILD_KEYS, type) ? CHILD_KEYS[type] : undefined;
}
